-- PUBG نۇپۇز سىستېمىسى: Supabase تولۇق ساندان ۋە Storage قۇرۇلمىسى
-- ئەسكەرتىش: بۇ كودنى كۆچۈرۈپ Supabase نىڭ SQL Editor قىسمىغا چاپلاپ Run كۇنۇپكىسىنى بېسىڭ
-- ========================================================

-- 1. كونا بەلگىلىمىلەرنى پاكىز تازىلاش (خاتالىق چىقىپ قالماسلىقى ئۈچۈن)
DROP POLICY IF EXISTS "submissions_insert" ON public.popularity_submissions;
DROP POLICY IF EXISTS "submissions_select" ON public.popularity_submissions;
DROP POLICY IF EXISTS "submissions_update" ON public.popularity_submissions;
DROP POLICY IF EXISTS "ئاشكارا ئۇچۇر تاپشۇرۇش" ON public.popularity_submissions;
DROP POLICY IF EXISTS "ئاشكارا ئۇچۇر كۆرۈش" ON public.popularity_submissions;
DROP POLICY IF EXISTS "ئۇچۇر يېڭىلاشقا رۇخسەت" ON public.popularity_submissions;

DROP POLICY IF EXISTS "bot_users_all" ON public.bot_users;

DROP POLICY IF EXISTS "storage_insert" ON storage.objects;
DROP POLICY IF EXISTS "storage_select" ON storage.objects;
DROP POLICY IF EXISTS "ھەممە ئادەم سۈرەت يوللىيالايدۇ" ON storage.objects;
DROP POLICY IF EXISTS "ھەممە ئادەم سۈرەت كۆرەلەيدۇ" ON storage.objects;

-- 2. نۇپۇز ئۇچۇرلىرى جەدۋىلىنى قۇرۇش
CREATE TABLE IF NOT EXISTS public.popularity_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pubg_id VARCHAR(32) NOT NULL,
    amount NUMERIC NOT NULL,
    contact_info VARCHAR(128) DEFAULT NULL,
    screenshot_url TEXT DEFAULT NULL,
    status VARCHAR(20) DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. بوت ئابونتلىرى (ئىشلەتكۈچىلەر) جەدۋىلى (ئومۇمىي ئۇچۇر تارقىتىش ئۈچۈن)
CREATE TABLE IF NOT EXISTS public.bot_users (
    user_id BIGINT PRIMARY KEY,
    first_name VARCHAR(128) DEFAULT NULL,
    username VARCHAR(128) DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- كۆرسەتكۈچلەرنى قۇرۇش (ئىزدەش تېز بولۇشى ئۈچۈن)
CREATE INDEX IF NOT EXISTS idx_submissions_status ON public.popularity_submissions(status);
CREATE INDEX IF NOT EXISTS idx_submissions_created_at ON public.popularity_submissions(created_at DESC);

-- 4. بىخەتەرلىك تۈزۈمى (RLS) نى قوزغىتىش
ALTER TABLE public.popularity_submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bot_users ENABLE ROW LEVEL SECURITY;

-- نۇپۇز جەدۋىلىنىڭ رۇخسەتلىرى
CREATE POLICY "submissions_insert" ON public.popularity_submissions FOR INSERT TO anon, authenticated WITH CHECK (true);
CREATE POLICY "submissions_select" ON public.popularity_submissions FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "submissions_update" ON public.popularity_submissions FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);

-- ئابونتلار جەدۋىلىنىڭ رۇخسەتلىرى
CREATE POLICY "bot_users_all" ON public.bot_users FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- 5. Storage قۇتىسىنى (screenshots) قۇرۇش
INSERT INTO storage.buckets (id, name, public) 
VALUES ('screenshots', 'screenshots', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage سۈرەت يۈكلەش ۋە كۆرۈش رۇخسەتلىرى
CREATE POLICY "storage_insert" ON storage.objects FOR INSERT TO anon, authenticated WITH CHECK (bucket_id = 'screenshots');
CREATE POLICY "storage_select" ON storage.objects FOR SELECT TO anon, authenticated USING (bucket_id = 'screenshots');
